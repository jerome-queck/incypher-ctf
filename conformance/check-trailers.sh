# Assert that every commit in a range carries the attribution trailers this Organisation requires.
# It matters because `squash_merge_commit_message = "COMMIT_MESSAGES"` concatenates the commit
# bodies onto `main`, so a commit missing its trailer leaves a permanent, undisclosed message on
# the default branch, and a `Co-authored-by:` with a stray address misattributes it to a stranger
# or a non-existent account (#39).
#
#   sh conformance/check-trailers.sh <range>     e.g. sh …/check-trailers.sh origin/main..HEAD
#
# The range is a pull request's own commits, and only ever that — `base.sha..head.sha`, which is
# what the central workflow hands it. Pointed at the default branch it reports every squash commit
# there as failing, and that is the tool being misused rather than a finding: GitHub appends its
# own aggregated `Co-authored-by:` block when it squashes, so the contributor's trailers stop being
# the final lines at the moment of a merge nobody can edit (#93, ADR-0040). Nothing on `main` is a
# contributor's commit any more, and the rule is about the commits a contributor writes.
#
# Served from `Jerome-Group/.github` beside the conformance checker rather than inside it, and run
# by the same central workflow, so that every repository enforces the rule its `AGENTS.md` states
# rather than only the one repository that happened to build the check (#75, ADR-0032). Beside
# rather than inside because the checker's input is a directory and its fixtures are directories:
# trailers are a property of history, which no tree can answer (ADR-0030's own revisit clause).
#
# Through the interpreter, always, and never `./` — the Contents API that writes this file into
# the hub commits a plain blob and cannot set the executable bit. Same as the checker beside it.
#
# The failure is where the rule is taught, in full and including the allowlist: that is what lets
# `AGENTS.md` carry four lines instead of thirty (#68), since the detail then arrives at the
# moment it is wanted rather than in a document read once (ADR-0032).
#
# Read-only. Prints one line per offending commit naming what is wrong, and exits non-zero if any.
set -eu

# Spelled out rather than `${1:?…}`, which exits 1 in some shells and 2 in others — and 1 is the
# status this script reserves for commits that genuinely break the rule, the same split the
# checker beside it makes.
if [ $# -ne 1 ]; then
  printf 'usage: sh conformance/check-trailers.sh <range>\n' >&2
  exit 2
fi

range=$1

# The verified allowlist, as addresses: a `Co-authored-by:` may carry only these. The name beside
# the address is free to be bare or not, so it is the address that is checked — it is the address
# that would misattribute. This list is also what the failure prints, so the rule a contributor is
# taught and the rule they are held to cannot come apart.
allowed_coauthors='noreply@anthropic.com noreply@openai.com 198982749+Copilot@users.noreply.github.com'

# Commit authors whose commits are generated by a bot and cannot carry a trailer. Dependabot's
# pull requests still run CI — they auto-merge (ADR-0010) — so its commits are skipped rather than
# failed. Matched on the author GitHub gives the bot, which a human commit does not wear.
bot_authors='dependabot[bot]'

failures=0

fail() {
  sha=$1
  reason=$2
  printf 'FAIL  %s  %s\n' "$sha" "$reason"
  failures=$((failures + 1))
}

# Said out loud, for the reason the linkage check beside this one says its own: a skipped commit
# and a checked one both leave the run green, so the printed word is the only thing that tells an
# exemption from a pass. An exemption nobody can see is an exemption nobody notices widening.
skip() {
  sha=$1
  reason=$2
  printf 'skip  %s  %s\n' "$sha" "$reason"
}

# Captured before the loop, not piped into it: a `while read` on the right of a pipe runs in a
# subshell and would discard every failure it counted (the mistake ADR-0017 records catching).
commits=$(git rev-list "$range")

for sha in $commits; do
  short=$(git rev-parse --short "$sha")
  author=$(git show -s --format='%an' "$sha")

  # More than one parent is a merge commit, and a merge commit in a pull request's range is the
  # platform's rather than the contributor's: `strict_required_status_checks_policy = true` means a
  # branch behind `main` must be updated before it can merge, and the **Update branch** button
  # writes a `Merge branch 'main' into …` whose message GitHub composes and nobody can edit
  # (#93, ADR-0040). Held to the rule, it blocked live merges in two repositories over text no
  # contributor wrote — and the bot exemption below does not reach it, because that commit is
  # authored by whoever pressed the button.
  #
  # Two parents rather than the message text, which is the narrower and more honest test: a
  # contributor's commit cannot accidentally acquire a second parent, but it can very easily
  # mention a branch merge in its subject line.
  #
  # Parentage alone is not enough, though, and this is the half a first cut got wrong. A merge
  # commit can carry content of its own — a conflict resolved by hand, `-s ours`, `--no-commit`
  # and then an edit — and a skip on parentage alone would wave that content through undisclosed,
  # with no allowlist applied to any `Co-authored-by:` on it either. So the skip asks the combined
  # diff, which is empty exactly when the merge took its content from its parents and added
  # nothing: an ordinary Update-branch merge is skipped, and a merge somebody actually wrote into
  # is held to the rule like anything else they wrote.
  if [ "$(git show -s --format='%P' "$sha" | wc -w)" -gt 1 ] &&
    [ -z "$(git diff-tree --cc --name-only --no-commit-id "$sha")" ]; then
    skip "$short" "merge commit adding nothing of its own — its message is the platform's"
    continue
  fi

  bot=
  for candidate in $bot_authors; do
    [ "$author" = "$candidate" ] && bot=$candidate
  done
  if [ -n "$bot" ]; then
    skip "$short" "$bot is a bot — its commits are generated and cannot carry a trailer"
    continue
  fi

  # `--parse` returns only lines that form the trailing trailer block, so an `Assisted-by:` buried
  # in the body with prose after it is not seen here — which is exactly the "as its last lines"
  # requirement, enforced by not treating it as a trailer.
  trailers=$(git show -s --format='%B' "$sha" | git interpret-trailers --parse)

  printf '%s\n' "$trailers" | grep -qi '^Assisted-by:[[:space:]]*[^[:space:]]' ||
    fail "$short" 'no Assisted-by: trailer as its final lines'

  # Every Co-authored-by, if any, must carry an allowlisted address. Selected with `grep -i`
  # because git treats a trailer token case-insensitively — a lowercase `co-authored-by:` must not
  # slip the allowlist, and `grep -i` is portable where sed's case flag is not. A line with no
  # `<address>` yields an empty field, which is on no allowlist and so fails, as a malformed
  # trailer should. The loop is fed by a here-document, not a pipe, so `fail` counts in this shell
  # rather than a subshell that discards it (ADR-0017).
  coauthors=$(printf '%s\n' "$trailers" | grep -i '^Co-authored-by:' || true)
  while IFS= read -r line; do
    [ -n "$line" ] || continue
    email=$(printf '%s' "$line" | sed -n 's/.*<\(.*\)>.*/\1/p')
    case " $allowed_coauthors " in
      *" $email "*) ;;
      *) fail "$short" "Co-authored-by: <$email> is not a verified vendor address" ;;
    esac
  done <<EOF
$coauthors
EOF
done

if [ "$failures" -gt 0 ]; then
  # The whole rule, not a pointer to it. A contributor reading this has the failing commit in
  # front of them and no reason to go looking; a check that only says "see AGENTS.md" spends the
  # one moment the rule is wanted on an errand (ADR-0032).
  #
  # The allowlist is printed from the variable the check itself uses, so the message cannot teach
  # an address the check would then reject.
  printf '\n%d commit(s) are missing or misusing the attribution trailers.\n\n' "$failures" >&2

  cat >&2 <<'RULE'
Every commit message ends with an `Assisted-by:` trailer as its last, contiguous lines:

    Assisted-by: Claude Opus 5

It names the exact model that helped, with an effort suffix only where one was explicitly set —
a mode is never recorded as one. Wrote it yourself? Then it is this, on its own:

    Assisted-by: none

Never no trailer at all. Every commit says who helped, including the ones where the answer is
nobody: a rule where a missing line sometimes means "a human wrote this" and sometimes means
"somebody forgot" has disclosed nothing either time.

Add a `Co-authored-by:` beside it only for a model whose vendor address is verified, and with no
blank line between the two. A blank line ends the trailer block, so the check would see only what
follows it and report the commit as having no `Assisted-by:` at all:

    Assisted-by: Claude Opus 5
    Co-authored-by: Claude <noreply@anthropic.com>

These addresses are the whole allowlist. Any other one is rejected rather than trusted, because a
guessed address credits a stranger or an account that does not exist, permanently and on `main`:

RULE

  for address in $allowed_coauthors; do
    printf '    %s\n' "$address" >&2
  done

  printf '\nThe full rule, and how to widen the allowlist, is in CONTRIBUTING.md.\n' >&2
  exit 1
fi

printf 'ok    every commit in %s carries the attribution trailers\n' "$range"
